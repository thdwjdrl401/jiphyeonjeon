-- ADR-0011: 업로드 녹화강의의 batch STT 상태와 draft 자막을 core가 소유한다.

CREATE TABLE core.recorded_stt_job (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  recorded_video_id uuid NOT NULL REFERENCES core.recorded_video(id) ON DELETE CASCADE,
  source_asset_id uuid NOT NULL REFERENCES core.asset(id),
  attempt_no integer NOT NULL CHECK (attempt_no > 0),
  status varchar(20) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING', 'DISPATCHED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
  idempotency_key varchar(255) NOT NULL UNIQUE,
  publish_attempt_count integer NOT NULL DEFAULT 0,
  next_publish_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz NULL,
  total_chunk_count integer NULL CHECK (total_chunk_count IS NULL OR total_chunk_count >= 0),
  processed_chunk_count integer NOT NULL DEFAULT 0 CHECK (processed_chunk_count >= 0),
  model varchar(100) NOT NULL,
  language varchar(20) NOT NULL,
  failure_code varchar(100) NULL,
  last_error text NULL,
  started_at timestamptz NULL,
  finished_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (recorded_video_id, attempt_no)
);

CREATE UNIQUE INDEX uq_recorded_stt_active_job
  ON core.recorded_stt_job (recorded_video_id)
  WHERE status IN ('PENDING', 'DISPATCHED', 'RUNNING');

CREATE INDEX ix_recorded_stt_dispatch
  ON core.recorded_stt_job (status, next_publish_at);

CREATE TABLE core.recorded_caption_track (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  recorded_video_id uuid NOT NULL UNIQUE REFERENCES core.recorded_video(id) ON DELETE CASCADE,
  status varchar(20) NOT NULL DEFAULT 'NOT_REQUESTED'
    CHECK (status IN ('NOT_REQUESTED', 'PENDING', 'PROCESSING', 'READY', 'EMPTY', 'FAILED')),
  publication_status varchar(20) NOT NULL DEFAULT 'NOT_AVAILABLE'
    CHECK (publication_status IN ('NOT_AVAILABLE', 'DRAFT', 'PUBLISHED')),
  active_job_id uuid NULL REFERENCES core.recorded_stt_job(id) ON DELETE SET NULL,
  model varchar(100) NULL,
  language varchar(20) NULL,
  duration_ms bigint NULL CHECK (duration_ms IS NULL OR duration_ms >= 0),
  segment_count integer NOT NULL DEFAULT 0 CHECK (segment_count >= 0),
  failure_code varchar(100) NULL,
  started_at timestamptz NULL,
  ready_at timestamptz NULL,
  published_at timestamptz NULL,
  version bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE core.recorded_stt_chunk (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id uuid NOT NULL REFERENCES core.recorded_stt_job(id) ON DELETE CASCADE,
  chunk_index integer NOT NULL CHECK (chunk_index >= 0),
  source_start_ms bigint NOT NULL CHECK (source_start_ms >= 0),
  source_end_ms bigint NOT NULL CHECK (source_end_ms > source_start_ms),
  source_sha256 varchar(64) NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
  payload_sha256 varchar(64) NOT NULL CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
  segment_count integer NOT NULL CHECK (segment_count >= 0),
  received_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (job_id, chunk_index)
);

CREATE TABLE core.recorded_caption_segment (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  track_id uuid NOT NULL REFERENCES core.recorded_caption_track(id) ON DELETE CASCADE,
  job_id uuid NOT NULL REFERENCES core.recorded_stt_job(id) ON DELETE CASCADE,
  chunk_index integer NOT NULL CHECK (chunk_index >= 0),
  local_segment_index integer NOT NULL CHECK (local_segment_index >= 0),
  start_ms bigint NOT NULL CHECK (start_ms >= 0),
  end_ms bigint NOT NULL CHECK (end_ms > start_ms),
  text text NOT NULL CHECK (char_length(text) BETWEEN 1 AND 4000),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (job_id, chunk_index, local_segment_index)
);

CREATE INDEX ix_recorded_caption_segment_track_time
  ON core.recorded_caption_segment (track_id, start_ms);

COMMENT ON TABLE core.recorded_caption_track IS
  '녹화강의 자막의 독립 처리/게시 상태. STT 성공 결과는 DRAFT로만 활성화한다.';
COMMENT ON TABLE core.recorded_stt_job IS
  '녹화강의 원본 MP4 batch STT 시도 이력이며 ingestion.transcribe dispatch source.';
COMMENT ON TABLE core.recorded_stt_chunk IS
  'worker가 멱등 전송한 청크 receipt와 원본/본문 checksum.';
COMMENT ON TABLE core.recorded_caption_segment IS
  '원본 MP4의 0ms 상대 시간축으로 저장한 녹화강의 자막 후보.';
