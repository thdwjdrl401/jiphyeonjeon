#!/bin/sh
set -eu

usage() {
    echo "usage: configure-gpu-ec2-tunnels.sh /absolute/path/to/key.pem user@ec2-host [--start]" >&2
    exit 2
}

SSH_KEY_SOURCE="${1:-}"
SSH_TARGET_VALUE="${2:-}"
ACTION="${3:-}"

if [ "$#" -lt 2 ] || [ "$#" -gt 3 ]; then
    usage
fi
case "$ACTION" in
    ""|--start)
        ;;
    *)
        usage
        ;;
esac
case "$SSH_KEY_SOURCE" in
    /*)
        ;;
    *)
        echo "SSH key source must be an absolute path" >&2
        exit 2
        ;;
esac
case "$SSH_TARGET_VALUE" in
    -*|*[!A-Za-z0-9@._:-]*|*@*@*|@*|*@)
        echo "SSH target must be a safe user@host value" >&2
        exit 2
        ;;
    ?*@?*)
        ;;
    *)
        echo "SSH target must be in user@host form" >&2
        exit 2
        ;;
esac

if [ ! -f "$SSH_KEY_SOURCE" ] || [ ! -r "$SSH_KEY_SOURCE" ]; then
    echo "SSH key source is not a readable regular file" >&2
    exit 1
fi
for command_name in chmod install mktemp readlink; do
    if ! command -v "$command_name" >/dev/null 2>&1; then
        echo "required command is missing: $command_name" >&2
        exit 1
    fi
done

validate_port() {
    port_value="$1"
    port_name="$2"
    case "$port_value" in
        ''|*[!0-9]*)
            echo "$port_name must be an integer port" >&2
            exit 1
            ;;
    esac
    if [ "$port_value" -lt 1 ] || [ "$port_value" -gt 65535 ]; then
        echo "$port_name must be between 1 and 65535" >&2
        exit 1
    fi
}

CONFIG_DIR="${LIVECLASS_CONFIG_DIR:-$HOME/.config/liveclass}"
USER_PREFIX="${LIVECLASS_USER_PREFIX:-$HOME/.local}"
KEY_DIR="$CONFIG_DIR/ssh"
INSTALLED_KEY="$KEY_DIR/gpu-to-ec2.pem"
REALTIME_TUNNEL_ENV="$CONFIG_DIR/realtime-agent-tunnels.env"
BGE_TUNNEL_ENV="$CONFIG_DIR/bge-tunnel.env"

case "$CONFIG_DIR:$USER_PREFIX" in
    *[!A-Za-z0-9_./:-]*)
        echo "configuration and user-prefix paths must not contain shell metacharacters" >&2
        exit 1
        ;;
esac

LIVEKIT_LOCAL_PORT="${LIVEKIT_LOCAL_PORT:-7443}"
LIVEKIT_REMOTE_PORT="${LIVEKIT_REMOTE_PORT:-7443}"
REDIS_LOCAL_PORT="${REDIS_LOCAL_PORT:-4000}"
REDIS_REMOTE_PORT="${REDIS_REMOTE_PORT:-4000}"
TURN_LOCAL_PORT="${TURN_LOCAL_PORT:-3478}"
TURN_REMOTE_PORT="${TURN_REMOTE_PORT:-3478}"
HEALTH_LOCAL_PORT="${HEALTH_LOCAL_PORT:-8081}"
HEALTH_REMOTE_PORT="${HEALTH_REMOTE_PORT:-18081}"
BGE_LOCAL_PORT="${BGE_LOCAL_PORT:-8020}"
BGE_EC2_PORT="${BGE_EC2_PORT:-18020}"
BGE_READY_TIMEOUT_SECONDS="${BGE_READY_TIMEOUT_SECONDS:-5}"

validate_port "$LIVEKIT_LOCAL_PORT" LIVEKIT_LOCAL_PORT
validate_port "$LIVEKIT_REMOTE_PORT" LIVEKIT_REMOTE_PORT
validate_port "$REDIS_LOCAL_PORT" REDIS_LOCAL_PORT
validate_port "$REDIS_REMOTE_PORT" REDIS_REMOTE_PORT
validate_port "$TURN_LOCAL_PORT" TURN_LOCAL_PORT
validate_port "$TURN_REMOTE_PORT" TURN_REMOTE_PORT
validate_port "$HEALTH_LOCAL_PORT" HEALTH_LOCAL_PORT
validate_port "$HEALTH_REMOTE_PORT" HEALTH_REMOTE_PORT
validate_port "$BGE_LOCAL_PORT" BGE_LOCAL_PORT
validate_port "$BGE_EC2_PORT" BGE_EC2_PORT
validate_port "$BGE_READY_TIMEOUT_SECONDS" BGE_READY_TIMEOUT_SECONDS

umask 077
install -d -m 0700 "$CONFIG_DIR" "$KEY_DIR"
source_key_real="$(readlink -f "$SSH_KEY_SOURCE")"
installed_key_real="$(readlink -f "$INSTALLED_KEY" 2>/dev/null || true)"
if [ "$source_key_real" != "$installed_key_real" ]; then
    install -m 0600 "$SSH_KEY_SOURCE" "$INSTALLED_KEY"
else
    chmod 0600 "$INSTALLED_KEY"
fi

temporary_dir="$(mktemp -d "${TMPDIR:-/tmp}/liveclass-gpu-ec2-tunnels.XXXXXX")"
cleanup() {
    rm -rf -- "$temporary_dir"
}
trap cleanup EXIT HUP INT TERM

realtime_candidate="$temporary_dir/realtime-agent-tunnels.env"
{
    echo "# Generated by configure-gpu-ec2-tunnels.sh. Keep this file chmod 0600."
    echo "SSH_KEY=$INSTALLED_KEY"
    echo "SSH_TARGET=$SSH_TARGET_VALUE"
    echo "LIVEKIT_LOCAL_PORT=$LIVEKIT_LOCAL_PORT"
    echo "LIVEKIT_REMOTE_PORT=$LIVEKIT_REMOTE_PORT"
    echo "REDIS_LOCAL_PORT=$REDIS_LOCAL_PORT"
    echo "REDIS_REMOTE_PORT=$REDIS_REMOTE_PORT"
    echo "TURN_LOCAL_PORT=$TURN_LOCAL_PORT"
    echo "TURN_REMOTE_PORT=$TURN_REMOTE_PORT"
    echo "HEALTH_LOCAL_PORT=$HEALTH_LOCAL_PORT"
    echo "HEALTH_REMOTE_PORT=$HEALTH_REMOTE_PORT"
    echo "HEALTH_BIND_HOST=127.0.0.1"
} >"$realtime_candidate"

bge_candidate="$temporary_dir/bge-tunnel.env"
{
    echo "# Generated by configure-gpu-ec2-tunnels.sh. Keep this file chmod 0600."
    echo "SSH_KEY=$INSTALLED_KEY"
    echo "SSH_TARGET=$SSH_TARGET_VALUE"
    echo "BGE_LOCAL_PORT=$BGE_LOCAL_PORT"
    echo "BGE_EC2_PORT=$BGE_EC2_PORT"
    echo "BGE_READY_TIMEOUT_SECONDS=$BGE_READY_TIMEOUT_SECONDS"
} >"$bge_candidate"

install -m 0600 "$realtime_candidate" "$REALTIME_TUNNEL_ENV"
install -m 0600 "$bge_candidate" "$BGE_TUNNEL_ENV"

echo "configured realtime-agent and BGE tunnels under $CONFIG_DIR"
echo "register the EC2 host key in ~/.ssh/known_hosts before starting supervisors"

if [ "$ACTION" = "--start" ]; then
    realtime_supervisor="$USER_PREFIX/bin/liveclass-realtime-agent-supervisor"
    bge_supervisor="$USER_PREFIX/bin/liveclass-bge-runtime-supervisor"
    if [ ! -x "$realtime_supervisor" ] || [ ! -x "$bge_supervisor" ]; then
        echo "install both rootless supervisors before using --start" >&2
        exit 1
    fi
    "$realtime_supervisor" start-tunnel
    "$bge_supervisor" start-tunnel
fi
